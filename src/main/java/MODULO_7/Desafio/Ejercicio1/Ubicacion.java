package MODULO_7.Desafio.Ejercicio1;

public class Ubicacion{
    private int fila;
    private int columna;

    public Ubicacion(int fila, int columna){
        this.fila = fila;
        this.columna = columna;
    }

    public int getFila(){
        return fila;
    }

    public int getColumna(){
        return columna;
    }
}
